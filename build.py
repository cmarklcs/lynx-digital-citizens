"""Build Lynx Digital Citizens.

Reads data/content.json and data/teacher.json, records every student-facing
sentence with the Mac's System voice (set to Siri) into site/audio/, and writes
site/js/content.js for the page to load.

    python3 build.py            # record anything new, then write content.js
    VOICE=Samantha python3 build.py
"""
import hashlib, json, os, re, subprocess
from pathlib import Path

ROOT = Path(__file__).parent
SITE = ROOT / "site"
content = json.loads((ROOT / "data/content.json").read_text())
teacher = json.loads((ROOT / "data/teacher.json").read_text())

# Keys whose values are never spoken.
SKIP = {"emoji", "id", "bin", "color", "type", "kind", "from", "to", "item", "center", "layout", "numbers", "symbols"}

def spoken(node, key=None):
    if key in SKIP:
        return
    if isinstance(node, str):
        if re.search(r"[A-Za-z0-9]", node):
            yield node
    elif isinstance(node, list):
        for x in node:
            yield from spoken(x, key)
    elif isinstance(node, dict):
        for k, v in node.items():
            yield from spoken(v, k)

texts = list(spoken(content))
for w in content["weeks"]:
    texts.append(f"Week {w['n']}. {w['kidTitle']}")
    for word in w["words"]:
        texts.append(f"{word['word']}. {word['meaning']}.")
texts = list(dict.fromkeys(texts))

VOICE = os.environ.get("VOICE", "system")
RATE = os.environ.get("RATE", "165")
(SITE / "audio").mkdir(parents=True, exist_ok=True)

def clean(t):
    # strip emoji so the voice doesn't read their names
    return re.sub(r"[\U0001F000-\U0001FAFF☀-➿️‍]", "", t).strip()

audio, made, failed = {}, 0, []
for text in texts:
    name = hashlib.sha1(f"{VOICE}|{RATE}|{text}".encode()).hexdigest()[:14] + ".m4a"
    out = SITE / "audio" / name
    if not out.exists():
        for attempt in range(3):
            try:
                subprocess.run(["say", *([] if VOICE == "system" else ["-v", VOICE]), "-r", RATE,
                                "--file-format=m4af", "--data-format=aac@22050", "--channels=1",
                                "--bit-rate=32000", "-o", str(out), clean(text)], check=True, timeout=30)
                made += 1
                break
            except (subprocess.TimeoutExpired, subprocess.CalledProcessError):
                subprocess.run(["pkill", "-x", "say"])
                out.unlink(missing_ok=True)
        else:
            failed.append(text)
    if out.exists():
        audio[text] = name

# remove recordings nothing uses any more
used = set(audio.values())
for f in (SITE / "audio").glob("*.m4a"):
    if f.name not in used:
        f.unlink()

js = ("/* Generated by build.py from data/*.json. Edit the JSON, not this file. */\n"
      f"const CONTENT = {json.dumps(content, ensure_ascii=False)};\n"
      f"const TEACHER = {json.dumps(teacher, ensure_ascii=False)};\n"
      f"const AUDIO = {json.dumps(audio, ensure_ascii=False)};\n")
(SITE / "js/content.js").write_text(js)

print(f"{len(texts)} spoken lines, {made} newly recorded, {len(audio)} with audio")
if failed:
    print("could not record:\n  " + "\n  ".join(failed))
